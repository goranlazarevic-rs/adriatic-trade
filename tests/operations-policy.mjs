import assert from 'node:assert/strict';
import fs from 'node:fs';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url),{parse}=require(process.env.YAML_MODULE_PATH||'yaml');
const workflow=parse(fs.readFileSync('.github/workflows/operations.yml','utf8'));
assert.deepEqual(Object.keys(workflow.on).sort(),['schedule','workflow_dispatch']);
assert.equal(workflow.jobs.hosting.environment.name,'worker-production');
assert.equal(workflow.jobs.hosting.concurrency['cancel-in-progress'],false);
const hosting=workflow.jobs.hosting.steps;
assert.equal(hosting.filter(s=>s.run==='bash scripts/check-worker-release.sh').length,2);
assert.ok(hosting.find(s=>s.id==='cutover').run.includes('"paused"'));
assert.ok(hosting.find(s=>s.id==='cutover').run.includes('ops/hosting.py rollback'));
const backup=workflow.jobs.operations.steps.find(s=>s.id==='backup');
assert.equal(backup.with['retention-days'],30);
assert.equal(backup.with['if-no-files-found'],'error');
assert.deepEqual(backup.with.path.trim().split('\n'),['.ops-private/adriatic-trade.atbak','.ops-private/adriatic-trade.atbak.sha256']);
const collection=workflow.jobs.operations.steps.find(s=>s.id==='collect').run;
assert.ok(collection.includes('ops/seal.mjs seal'));
assert.ok(!JSON.stringify(workflow).includes('recovery-private.pem'));
const release=parse(fs.readFileSync('.github/workflows/deploy-worker.yml','utf8'));
for(const file of ['ops/**','.github/workflows/operations.yml','scripts/build-web.mjs','wrangler.web.json'])assert.ok(release.on.pull_request.paths.includes(file));
console.log('Operations workflow: protected hosting, immutable SHA, encrypted artifacts and paused cutover verified');
